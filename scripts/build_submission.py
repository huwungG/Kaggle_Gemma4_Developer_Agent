"""Validate an agent directory with the official harness, zip it, and generate a Kaggle submit notebook.

Usage:
    .venv/bin/python scripts/build_submission.py agents/baseline_v1

Outputs:
    submissions/<name>.zip              the archive Kaggle scores
    notebooks/<name>/<name>.ipynb       CPU notebook that writes /kaggle/working/submission.zip
    notebooks/<name>/kernel-metadata.json

The notebook embeds the agent's text files, so text-only agents need no extra dataset.
Agents with adapters/ need the weights uploaded as a Kaggle dataset first (not supported yet).
"""

import argparse
import json
import re
import sys
import zipfile
from pathlib import Path

from adk_submission import ModelRegistry, compile_submission, discover_declared_models, validate_directory
from google.adk.models.lite_llm import LiteLlm
from swegemma.config import ALLOWED_SUBMISSION_EXTENSIONS, MAX_SUBMISSION_SIZE_BYTES, build_submission_limits

ROOT = Path(__file__).resolve().parent.parent
MODEL = "gemma-4-31b-it-qat-w4a16-ct"
KAGGLE_USER = "dophuchung"
COMPETITION = "gemma-4-developer-agent"


# Stand-ins with the real tool signatures: compiling only checks names and schemas.
def run_command(command: str) -> str: ...
def read_file(filepath: str, start_line: int | None = None, end_line: int | None = None) -> str: ...
def write_file(filepath: str, content: str) -> str: ...
def edit_file(filepath: str, old_string: str, new_string: str, allow_multiple: bool = False) -> str: ...
def submit_patch() -> str: ...
def get_status() -> str: ...
def get_code_neighbors(node: str, edge_type: str | None = None, max_neighbors: int = 50) -> str: ...
def search_similar_code(query: str, k: int = 10) -> str: ...
def get_code_subgraph(nodes: list[str]) -> str: ...


TOOLS = {f.__name__: f for f in [run_command, read_file, write_file, edit_file, submit_patch, get_status,
                                 get_code_neighbors, search_similar_code, get_code_subgraph]}


def validate(agent_dir: Path) -> None:
    files = [p for p in agent_dir.rglob("*") if p.is_file()]
    for p in files:
        assert p.suffix.lower() in ALLOWED_SUBMISSION_EXTENSIONS, f"disallowed extension: {p}"
        assert not p.is_symlink(), f"symlink not allowed: {p}"
    total = sum(p.stat().st_size for p in files)
    assert total < MAX_SUBMISSION_SIZE_BYTES, f"too large: {total} bytes"

    # ADK interpolates {identifier} in instructions from session state; an unknown key crashes the run.
    for p in agent_dir.rglob("*.md"):
        if p.parent.name == "prompts" or p.name == "SKILL.md":
            for m in re.finditer(r"\{[A-Za-z_][A-Za-z0-9_]*\??\}", p.read_text()):
                if m.group(0) not in ("{problem_description}", "{hints?}", "{problem_description?}"):
                    print(f"WARNING: {p.relative_to(agent_dir)} contains template placeholder {m.group(0)}")

    limits, constraints = build_submission_limits()
    models = ModelRegistry()
    models.register(MODEL, LiteLlm(model=f"openai/{MODEL}", api_base="http://127.0.0.1:9/v1", api_key="EMPTY"))
    validate_directory(agent_dir, limits)
    declared = discover_declared_models(agent_dir, lambda m: m.strip().split("/")[-1])
    assert declared == {MODEL}, f"declared models {declared} != {{{MODEL!r}}}"
    agent = compile_submission(agent_dir, TOOLS, models, limits=limits, generation_constraints=constraints)
    print(f"ok: compiled root agent {agent.name!r}, {len(files)} files, {total / 1e6:.2f} MB")


def build_zip(agent_dir: Path, name: str) -> Path:
    out = ROOT / "submissions" / f"{name}.zip"
    out.parent.mkdir(exist_ok=True)
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as zf:
        for p in sorted(agent_dir.rglob("*")):
            if p.is_file():
                zf.write(p, p.relative_to(agent_dir).as_posix())
    print(f"wrote {out.relative_to(ROOT)}")
    return out


def build_notebook(agent_dir: Path, name: str) -> Path:
    if (agent_dir / "adapters").exists():
        sys.exit("adapters/ present: upload weights as a dataset and extend build_notebook first")
    files = {p.relative_to(agent_dir).as_posix(): p.read_text() for p in sorted(agent_dir.rglob("*")) if p.is_file()}
    code = (
        "import json, zipfile\nfrom pathlib import Path\n\n"
        f"FILES = json.loads({json.dumps(json.dumps(files, indent=1))})\n\n"
        "out = Path('/kaggle/working/submission.zip')\n"
        "with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zf:\n"
        "    for rel, text in sorted(FILES.items()):\n"
        "        zf.writestr(rel, text)\n"
        "print(out, out.stat().st_size, 'bytes')\n"
        "print('\\n'.join(zipfile.ZipFile(out).namelist()))\n"
    )
    nb = {
        "cells": [
            {"cell_type": "markdown", "metadata": {}, "source": [f"# {name}\n\nWrites the agent config to `/kaggle/working/submission.zip`. Generated by `scripts/build_submission.py`."]},
            {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": code.splitlines(keepends=True)},
        ],
        "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"}},
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    slug = f"g4-agent-{name.replace('_', '-')}"
    nb_dir = ROOT / "notebooks" / name
    nb_dir.mkdir(parents=True, exist_ok=True)
    (nb_dir / f"{slug}.ipynb").write_text(json.dumps(nb, indent=1))
    meta = {
        "id": f"{KAGGLE_USER}/{slug}",
        "title": slug,
        "code_file": f"{slug}.ipynb",
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": False,
        "enable_tpu": False,
        "enable_internet": False,
        "dataset_sources": [],
        "competition_sources": [COMPETITION],
        "kernel_sources": [],
        "model_sources": [],
    }
    (nb_dir / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {nb_dir.relative_to(ROOT)}/ (kernel {meta['id']})")
    return nb_dir


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("agent_dir", type=Path)
    args = ap.parse_args()
    agent_dir = args.agent_dir.resolve()
    name = agent_dir.name
    validate(agent_dir)
    build_zip(agent_dir, name)
    build_notebook(agent_dir, name)


if __name__ == "__main__":
    main()
